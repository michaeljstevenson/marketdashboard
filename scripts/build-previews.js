#!/usr/bin/env node
// Stages unmerged PR pages under /preview/ (password-gated by
// netlify/edge-functions/preview-gate.js) so they can be reviewed on the live
// site before being merged into the public nav.
//
// preview/manifest.json lists each PR: its branch, the pages it adds, the
// functions they need and their /api routes. For each entry this script:
//   - copies the PR's new pages from origin/<branch> into preview/, pointing
//     links between preview pages at /preview/ and marking them noindex
//   - copies the PR's new functions into netlify/functions/
//   - writes the PR's /api routes into the marked block in netlify.toml
//     (no schedules: preview jobs only run when started by hand)
//   - rebuilds preview/index.html
// build-schedule-page.js skips every function listed here, so previews stay
// off the public Data Pull Schedule and out of the health check.
//
// To promote a PR: merge it, delete its entry from the manifest, rerun this.
//
//   git fetch origin && node scripts/build-previews.js

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.join(__dirname, "..");
const DIR = path.join(ROOT, "preview");
const MANIFEST = JSON.parse(fs.readFileSync(path.join(DIR, "manifest.json"), "utf8"));
const TOML = path.join(ROOT, "netlify.toml");
const BEGIN = "# BEGIN preview routes (generated by scripts/build-previews.js)";
const END = "# END preview routes";

const show = (branch, file) =>
  execFileSync("git", ["show", `origin/${branch}:${file}`], { cwd: ROOT, encoding: "utf8", maxBuffer: 1 << 26 });
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const previewPages = new Set(MANIFEST.flatMap((e) => e.pages.map((p) => p.file)));

function stage(html, entry) {
  html = html.replace(/(href|src)="\/([A-Za-z0-9-]+\.html)(#[^"]*)?"/g, (m, attr, file, hash) =>
    previewPages.has(file) ? `${attr}="/preview/${file}${hash || ""}"` : m);
  html = html.replace(/src="date-format\.js"/g, 'src="/date-format.js"');
  html = html.replace(/<head>/i, '<head>\n<meta name="robots" content="noindex">');
  const bar =
    `<div style="position:sticky;top:0;z-index:9999;display:flex;gap:14px;justify-content:center;flex-wrap:wrap;` +
    `padding:6px 16px;background:#b8860b;color:#fff;font:600 12px/1.4 system-ui,sans-serif">` +
    `<span>Preview &middot; PR #${entry.pr}</span>` +
    `<a href="https://github.com/michaeljstevenson/marketdashboard/pull/${entry.pr}" style="color:#fff" target="_blank" rel="noopener">View PR</a>` +
    `<a href="/preview/" style="color:#fff">All previews</a></div>`;
  return html.replace(/(<body[^>]*>)/i, `$1\n${bar}`);
}

let pageCount = 0;
for (const entry of MANIFEST) {
  for (const { file } of entry.pages) {
    fs.writeFileSync(path.join(DIR, file), stage(show(entry.branch, file), entry));
    pageCount++;
  }
  for (const fn of entry.functions) {
    fs.writeFileSync(path.join(ROOT, "netlify", "functions", fn), show(entry.branch, `netlify/functions/${fn}`));
  }
}

const routes = MANIFEST.flatMap((e) => e.redirects)
  .map((r) => `[[redirects]]\n  from = "${r.from}"\n  to = "${r.to}"\n  status = 200\n`)
  .join("\n");
let toml = fs.readFileSync(TOML, "utf8");
const block = `${BEGIN}\n${routes}${END}`;
toml = toml.includes(BEGIN)
  ? toml.replace(new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`), block)
  : toml.replace(/(\n\[\[redirects\]\])/, `\n${block}\n$1`);
fs.writeFileSync(TOML, toml);

const rows = MANIFEST.map((e) => `<section>
<h2><a href="https://github.com/michaeljstevenson/marketdashboard/pull/${e.pr}" target="_blank" rel="noopener">PR #${e.pr}</a> ${esc(e.title)}</h2>
<ul>${e.pages.map((p) => `<li><a href="/preview/${p.file}">${esc(p.title)}</a></li>`).join("")}</ul>
</section>`).join("\n");

fs.writeFileSync(path.join(DIR, "index.html"), `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex"><title>Previews | Michael J. Stevenson</title>
<style>
:root{--ground:#f4f3ef;--ink:#1b1e1c;--ink-dim:#5c5f59;--line:#e2dfd5;--accent:#8a6a1f}
@media (prefers-color-scheme:dark){:root{--ground:#16150f;--ink:#ece9e1;--ink-dim:#9a978c;--line:#33302a;--accent:#d9b25c}}
body{margin:0;background:var(--ground);color:var(--ink);font-family:"IBM Plex Sans",system-ui,sans-serif}
.wrap{max-width:860px;margin:0 auto;padding:40px 16px 60px}
h1{font-size:1.8rem;font-weight:600;margin:0 0 6px}
.sub{color:var(--ink-dim);font-size:.9rem;margin:0 0 28px}
section{border-top:1px solid var(--line);padding:14px 0}
h2{font-size:1rem;font-weight:600;margin:0 0 8px}
h2 a{color:var(--accent);text-decoration:none;margin-right:6px}
ul{margin:0;padding-left:18px}
li{margin:4px 0;font-size:.95rem}
li a{color:var(--ink)}
</style></head><body><div class="wrap">
<h1>Previews</h1>
<p class="sub">${pageCount} pages from ${MANIFEST.length} open pull requests &middot; <a href="/statistical-engine" style="color:var(--ink-dim)">Statistical Engine</a></p>
${rows}
</div></body></html>
`);

console.log(`preview/: ${pageCount} pages from ${MANIFEST.length} PRs, ${MANIFEST.flatMap((e) => e.redirects).length} routes`);
